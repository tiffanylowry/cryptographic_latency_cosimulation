/*
 * ns3_cosim_300.cc
 *
 * Phase 4: NS-3 HELICS co-simulation federate for the full-scale 300-house
 * AMI model. Replaces Phase 2/3's flat 5-node CSMA LAN with a 4-tier
 * hierarchy that mirrors the real IEEE-13-node-with-houses feeder's own
 * service-transformer geography:
 *
 *   Tier 0 (1):   substation aggregator      -- meter:650
 *   Tier 1 (7):   primary-bus gateways       -- buses 611,634,645,646,652,675,692
 *   Tier 2 (15):  neighborhood concentrators -- trip_meter1..15
 *   Tier 3 (300): house meters               -- house_m<N>_<k>
 *
 * Links: Tier0<->Tier1 PointToPoint (FAN backhaul, 1 per gateway); Tier1<->
 * Tier2 CSMA (1 segment per gateway, its concentrators); Tier2<->Tier3 CSMA
 * (1 segment per concentrator, its 20 houses).
 *
 * The topology itself (which house belongs to which concentrator, which
 * concentrator to which gateway) is loaded at runtime from
 * ns3/topology_config.txt (generated by scripts/build_topology_manifest.py
 * + scripts/generate_ns3_topology_config.py from the real GLM) -- nothing
 * about the fan-out counts is hardcoded here.
 *
 * Crypto model (Phase 3, unchanged mechanism, generalized to 3 hops): every
 * relay (gateway, concentrator) decrypts an inbound packet using its own
 * resolved profile, then re-encrypts (same profile) before forwarding --
 * 6 injection points total (was 2 in Phase 3's flat model). Each fan-out
 * point's encryption cost is either applied once in parallel across all
 * children, or serialized (cumulative) across them, per that node's
 * resolved serial_encrypt setting -- this is the mechanism that turns
 * "AES-GCM adds 272ms per device" into "~5.4s serialized per 20-house
 * neighborhood" at a concentrator, the headline effect this phase exists
 * to make measurable.
 *
 * Build: bash build_ns3_federate_300.sh
 * Run:   bash ../run/run_cosim_ieee13_300.sh
 */

