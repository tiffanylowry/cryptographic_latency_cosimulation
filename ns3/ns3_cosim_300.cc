// The curtailment EMA's alpha is tuned relative to a specific control
// period -- 0.3 at the original 60s production cadence implies a real-world
// settling time constant tau = -60/ln(1-0.3) =~ 167.75s. g_smoothingAlpha
// defaults to a sentinel (-1.0 = "auto-derive") so that changing
// g_controlPeriodSec via --period= doesn't silently change the EMA's
// physical (wall-clock) responsiveness as a side effect; --smoothing-alpha=
// overrides the auto-derived value for deliberately testing non-equivalent
// dynamics.
static double g_smoothingAlpha = -1.0;
static const double BASELINE_PERIOD_SEC = 60.0;
static const double BASELINE_SMOOTHING_ALPHA = 0.3;

static double ComputeAutoSmoothingAlpha(double periodSec)
{
    double tau = -BASELINE_PERIOD_SEC / std::log(1.0 - BASELINE_SMOOTHING_ALPHA);
    return 1.0 - std::exp(-periodSec / tau);
}

