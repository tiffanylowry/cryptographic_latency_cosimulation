#!/usr/bin/env python3
"""
generate_crypto_config.py

Generates ns3/crypto/crypto_config_300.txt from
gridlabd/topology_manifest.json. Extends the existing Phase 3 role catalog
(protection_relay, substation_aggregator, nan_gateway, residential_meter,
legacy_meter -- all reused verbatim, just gaining a serial_encrypt= key)
with one new role, nan_concentrator, and assigns a role to every node in
the 4-tier topology (1 aggregator + 7 gateways + 15 concentrators + 300
houses = 323 node entries).

Device-class split for the 300 houses (per the approved plan: "a
deterministic split... producing the full device-class spectrum
simultaneously"): hash(global_idx) % 10 determines the cohort --
  0-6 (70%): role=residential_meter (ARM32 default, ascon-aead128-arm32)
  7   (10%): explicit override -> ascon-aead128-msp16 (MSP430-class)
  8   (10%): explicit override -> ascon-aead128-avr8 (AVR8-class)
  9   (10%): role=legacy_meter (profile=none, unencrypted)
This is a plan-level design choice, not a fact from any source -- the
fractions/rule are named constants below, trivially adjustable.

The default toggle state (enabled=false) and default_profile are unchanged
from the existing crypto_config.txt -- CRYPTO_ENABLED env var / --crypto-
enabled CLI flag continue to work exactly as before.

rng_seed is written explicitly (default 1) rather than relying on
ns3_cosim_300.cc's C++ default -- makes the deterministic-by-default
behavior a visible, documented, adjustable setting in the generated file
instead of an implicit fallback. Override with --rng-seed to get a second
random realization for stability checks across seeds.

Usage:
    python3 generate_crypto_config.py <manifest.json> <config_out.txt> [--rng-seed N]
"""
import argparse
import json

MSP430_COHORT_PROFILE = "ascon-aead128-msp16"
AVR8_COHORT_PROFILE = "ascon-aead128-avr8"


def house_cohort(global_idx):
    bucket = global_idx % 10
    if bucket <= 6:
        return "residential_meter", None
    elif bucket == 7:
        return "residential_meter", MSP430_COHORT_PROFILE
    elif bucket == 8:
        return "residential_meter", AVR8_COHORT_PROFILE
    else:
        return "legacy_meter", None


def build_config(manifest, rng_seed):
    lines = []
    lines.append("# Generated by scripts/generate_crypto_config.py -- do not hand-edit.")
    lines.append("# Regenerate via the topology_manifest.json pipeline instead.")
    lines.append("")
    lines.append("enabled=false")
    lines.append("default_profile=ascon-aead128-arm32")
    lines.append("handshake_enabled=false")
    lines.append("handshake_profile=curve25519-ecdh-m0")
    lines.append(f"rng_seed={rng_seed}")
    lines.append("")

    lines.append("role.protection_relay.default_profile=aes-gcm-artix7")
    lines.append("role.protection_relay.tt_budget_ms=3")
    lines.append("role.protection_relay.serial_encrypt=false")
    lines.append("")
    lines.append("role.substation_aggregator.default_profile=aes-gcm-artix7")
    lines.append("role.substation_aggregator.tt_budget_ms=20")
    lines.append("role.substation_aggregator.serial_encrypt=false")
    lines.append("")
    lines.append("role.nan_gateway.default_profile=aes-gcm-arm32")
    lines.append("role.nan_gateway.tt_budget_ms=100")
    lines.append("role.nan_gateway.serial_encrypt=false")
    lines.append("")
    # New role for this phase. nan_gateway's aes-gcm-arm32 (Cortex-M figure)
    # is reused as the best available stand-in -- the benchmark table has no
    # Cortex-A entry (see ns3/crypto/README.md's Cortex-A gap note).
    lines.append("role.nan_concentrator.default_profile=ascon-aead128-arm32")
    lines.append("role.nan_concentrator.tt_budget_ms=100")
    lines.append("role.nan_concentrator.serial_encrypt=true")
    lines.append("")
    lines.append("role.residential_meter.default_profile=ascon-aead128-arm32")
    lines.append("role.residential_meter.tt_budget_ms=500")
    lines.append("role.residential_meter.serial_encrypt=true")
    lines.append("")
    lines.append("role.legacy_meter.default_profile=none")
    lines.append("role.legacy_meter.tt_budget_ms=1000")
    lines.append("role.legacy_meter.serial_encrypt=true")
    lines.append("")

    lines.append("node.aggregator.role=substation_aggregator")
    lines.append("")

    for g in manifest["gateways"]:
        lines.append(f"node.gw_{g['gateway_bus']}.role=nan_gateway")
    lines.append("")

    for c in manifest["concentrators"]:
        lines.append(f"node.conc_m{c['concentrator_idx']}.role=nan_concentrator")
    lines.append("")

    cohort_counts = {"residential_meter": 0, "legacy_meter": 0,
                      MSP430_COHORT_PROFILE: 0, AVR8_COHORT_PROFILE: 0}
    for h in manifest["houses"]:
        role, override_profile = house_cohort(h["global_idx"])
        node_key = h["house_name"]
        lines.append(f"node.{node_key}.role={role}")
        if override_profile is not None:
            lines.append(f"node.{node_key}.profile={override_profile}")
            cohort_counts[override_profile] += 1
        else:
            cohort_counts[role] += 1

    text = "\n".join(lines) + "\n"
    return text, cohort_counts


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("manifest_path")
    ap.add_argument("out_path")
    ap.add_argument("--rng-seed", type=int, default=1,
                     help="NS-3 RngSeedManager seed to write into the generated config (default: 1)")
    args = ap.parse_args()

    with open(args.manifest_path, "r") as f:
        manifest = json.load(f)

    text, cohort_counts = build_config(manifest, args.rng_seed)

    with open(args.out_path, "w") as f:
        f.write(text)

    total_nodes = 1 + manifest["num_gateways"] + manifest["num_concentrators"] + manifest["num_houses"]
    print(f"Wrote {args.out_path}: {total_nodes} node role/profile entries. rng_seed={args.rng_seed}")
    print(f"House device-class cohorts: {cohort_counts}")


if __name__ == "__main__":
    main()
