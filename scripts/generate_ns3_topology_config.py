#!/usr/bin/env python3
"""
generate_ns3_topology_config.py

Generates ns3/topology_config.txt from gridlabd/topology_manifest.json --
the runtime 4-tier topology description ns3_cosim.cc's LoadTopologyConfig()
reads at startup to build its NodeContainers and per-tier vectors. Same
hand-rolled key=value flat-file format as ns3/crypto/crypto_config.txt (no
JSON library is linked into the NS-3 scratch build -- see CLAUDE.md).

Gateway indices (1..7) are assigned in ascending bus-number order (matching
topology_manifest.json's own gateway ordering) and are what concentrators
reference -- NOT the real bus number itself, since bus numbers (611, 634,
...) aren't contiguous and don't make convenient 0-based vector indices.

helics_input_index values give the exact 0-based fed.getInput(i) index each
concentrator's load/voltage subscriptions live at, matching the exact
publication order generate_ns3_federate_config.py writes:
  0: total_load
  1: conc_1_load, 2: conc_1_voltage
  3: conc_2_load, 4: conc_2_voltage
  ... (2 inputs per concentrator, in concentrator_idx order)

Usage:
    python3 generate_ns3_topology_config.py <manifest.json> <topology_out.txt>
"""
import sys
import json


def main():
    if len(sys.argv) != 3:
        print(f"Usage: {sys.argv[0]} <manifest.json> <topology_out.txt>", file=sys.stderr)
        sys.exit(1)

    manifest_path, out_path = sys.argv[1], sys.argv[2]
    with open(manifest_path, "r") as f:
        manifest = json.load(f)

    gateway_idx_by_bus = {g["gateway_bus"]: i + 1 for i, g in enumerate(manifest["gateways"])}

    lines = []
    lines.append("# Generated by scripts/generate_ns3_topology_config.py -- do not hand-edit.")
    lines.append("# Regenerate via the topology_manifest.json pipeline instead.")
    lines.append("")
    lines.append(f"num_gateways={manifest['num_gateways']}")
    lines.append(f"num_concentrators={manifest['num_concentrators']}")
    lines.append(f"num_houses={manifest['num_houses']}")
    lines.append(f"houses_per_concentrator={manifest['houses_per_concentrator']}")
    lines.append("")

    for g in manifest["gateways"]:
        idx = gateway_idx_by_bus[g["gateway_bus"]]
        conc_list = ",".join(str(c) for c in g["concentrator_idx"])
        lines.append(f"gateway.{idx}.bus={g['gateway_bus']}")
        lines.append(f"gateway.{idx}.concentrators={conc_list}")
    lines.append("")

    for c in manifest["concentrators"]:
        n = c["concentrator_idx"]
        gw_idx = gateway_idx_by_bus[c["gateway_bus"]]
        load_input_idx = 1 + (n - 1) * 2
        voltage_input_idx = load_input_idx + 1
        lines.append(f"concentrator.{n}.gateway={gw_idx}")
        lines.append(f"concentrator.{n}.trip_meter={c['trip_meter']}")
        lines.append(f"concentrator.{n}.helics_load_key=conc_{n}_load")
        lines.append(f"concentrator.{n}.helics_voltage_key=conc_{n}_voltage")
        lines.append(f"concentrator.{n}.helics_input_index_load={load_input_idx}")
        lines.append(f"concentrator.{n}.helics_input_index_voltage={voltage_input_idx}")
    lines.append("")

    for h in manifest["houses"]:
        gi = h["global_idx"]
        lines.append(f"house.{gi}.name={h['house_name']}")
        lines.append(f"house.{gi}.zip={h['zip_name']}")
        lines.append(f"house.{gi}.concentrator={h['concentrator_idx']}")
        lines.append(f"house.{gi}.control_key=control_{h['house_name']}")

    text = "\n".join(lines) + "\n"

    with open(out_path, "w") as f:
        f.write(text)

    print(
        f"Wrote {out_path}: {manifest['num_gateways']} gateways, "
        f"{manifest['num_concentrators']} concentrators, {manifest['num_houses']} houses."
    )


if __name__ == "__main__":
    main()
